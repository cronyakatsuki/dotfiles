function chezmoiCommit(
  file: string,
  ctx: ExtensionContext,
  approved: Set<string>,
): void {
  try {
    const src = execSync(`chezmoi source-path "${file}" 2>/dev/null`, {
      encoding: "utf-8",
      stdio: ["pipe", "pipe", "pipe"],
    }).trim();
    if (!src || !existsSync(src)) return;

    const gitRoot = isInGitRepo(src);
    if (!gitRoot) return;

    // Secret scan on the source file (that's what gets committed)
    const secret = scanForSecrets(src);
    if (secret) {
      const tracked = isTrackedByGit(src, gitRoot);
      if (!tracked) {
        addToGitignore(gitRoot, src);
      }
      try {
        ctx.ui.notify(
          `safe-edit: ${secret} in chezmoi source ${basename(src)} — commit blocked${tracked ? " (file tracked, review manually)" : ", added to .gitignore"}`,
          "warning",
        );
      } catch {
        // ignore — still blocked
      }
      return;
    }

    const msg = `chore: update ${basename(file)}`;
    const approvalKey = `chezmoi:${src}`;
    const commit = () => {
      execFileSync("git", ["add", "--", src], { cwd: gitRoot, stdio: "pipe" });
      execFileSync("git", ["commit", "-m", msg, "--no-gpg-sign", "--", src], {
        cwd: gitRoot,
        stdio: "pipe",
      });
      try {
        ctx.ui.notify(`safe-edit: committed (chezmoi) ${basename(file)} — ${msg}`, "info");
      } catch {
        // ignore
      }
    };

    (async () => {
      if (approved.has(approvalKey)) return commit();
      let diff = "";
      try {
        diff = execSync(`git diff HEAD --no-color -- "${src}"`, {
          cwd: gitRoot,
          encoding: "utf-8",
          stdio: ["pipe", "pipe", "pipe"],
        }).trim();
      } catch {
        // ignore
      }
      const decision = await askCommitApproval(ctx, {
        tool: "chezmoi",
        file: src,
        message: msg,
        diff,
      });
      if (decision === "always") approved.add(approvalKey);
      if (decision === "commit" || decision === "always") commit();
    })().catch(() => {
      // chezmoi commit is best-effort — don't block the tool call
    });
  } catch {
    // best-effort — don't block the tool call
  }
}

async function commitIfManaged(
  file: string,
  ctx: ExtensionContext,
  approved: Set<string>,
): Promise<void> {
  // Precedence avoids double commits: yadm > chezmoi > plain git
  if (isYadmManaged(file)) {
    yadmCommit(file, ctx, approved);
    return;
  }
  if (isChezmoiManaged(file)) {
    chezmoiCommit(file, ctx, approved);
    return;
  }
  await gitCommitIfNeeded(file, ctx, approved);
}

// ---- Extension ----

export default function (pi: ExtensionAPI) {
  // "Always this session" approvals, reset when pi restarts (per session)
  const sessionApproved = new Set<string>();

  // Intercept tool calls to create backups BEFORE the tool runs
  pi.on("tool_call", async (event) => {
    // Handle edit tool
    if (isToolCallEventType("edit", event)) {
      const filePath = event.input.path;
      if (filePath) {
        const bak = createBackup(filePath);
        if (bak) {
          rotateBackups(filePath);
        }
      }
    }

    // Handle write tool
    if (isToolCallEventType("write", event)) {
      const filePath = event.input.path;
      if (filePath) {
        // For write, back up existing file if it exists
        const bak = createBackup(filePath);
        if (bak) {
          rotateBackups(filePath);
        }
      }
    }
  });

  // After tool execution, commit changes if managed
  pi.on("tool_result", async (event, ctx) => {
    if (event.toolName === "edit" || event.toolName === "write") {
      const input = event.input as { path?: string };
      if (input?.path) {
        await commitIfManaged(input.path, ctx, sessionApproved);
      }
    }
  });
}
