const MAX_BACKUPS = 5;
const SUMMARY_TIMEOUT_MS = 8000;
const SUMMARY_PAYLOAD_CAP = 8000; // chars of diff/content sent to the model
const DIFF_PREVIEW_LINES = 40; // max diff lines shown in the approval dialog

// Conventional Commits (cz_conventional_commits) validation
const CONVENTIONAL_TYPES =
  "feat|fix|docs|style|refactor|perf|test|build|ci|chore|revert";
const CONVENTIONAL_RE = new RegExp(
  `^(${CONVENTIONAL_TYPES})(\\([^)]*\\))?: \\S.*$`,
);

// ---- Helpers ----

function getBackupDir(file: string): string {
  const absFile = resolve(file);
  const home = process.env.HOME || "/home/crony";
  const dataHome = process.env.XDG_DATA_HOME || `${home}/.local/share`;
  // Encode the full absolute path so every file gets its own unique backup dir
  const safeName = absFile.replace(/^\//, "").replace(/\//g, "_");
  return `${dataHome}/safe-edit/backups/${safeName}`;
}

function createBackup(file: string): string | null {
  if (file.startsWith("/") === false) {
    file = resolve(file);
  }
  // Resolve through symlinks (for Stow-managed files)
  try {
    file = realpathSync(file);
  } catch {
    // path may not exist yet (e.g. a new write) — proceed without a backup
  }
  if (!existsSync(file)) return null;

  const bdir = getBackupDir(file);
  mkdirSync(bdir, { recursive: true });

  const ts = Date.now();
  const base = basename(file);
  const backupFile = `${bdir}/${base}.${ts}`;

  copyFileSync(file, backupFile);
  try {
    // Make backup read-only for user to prevent accidental edits
    chmodSync(backupFile, 0o600);
  } catch {
    // chmod may fail on some filesystems — the backup itself is what matters
  }

  return backupFile;
}

function rotateBackups(file: string): void {
  try {
    file = realpathSync(file);
  } catch {
    // nothing to resolve — use the path as-is
  }
  const bdir = getBackupDir(file);
  if (!existsSync(bdir)) return;

  const base = basename(file);

  try {
    const files = readdirSync(bdir).filter((f: string) =>
      f.startsWith(base + "."),
    );
    files.sort((a: string, b: string) => {
      const ta = parseInt(a.split(".").pop() || "0", 10);
      const tb = parseInt(b.split(".").pop() || "0", 10);
      return ta - tb;
    });

    if (files.length > MAX_BACKUPS) {
      const toDelete = files.slice(0, files.length - MAX_BACKUPS);
      for (const f of toDelete) {
        try {
          unlinkSync(`${bdir}/${f}`);
        } catch {
          // best-effort rotation — ignore individual failures
        }
      }
    }
  } catch {
    // readdir/rotation failure — ignore, backups are best-effort
  }
}

function isInGitRepo(file: string): string | null {
  let dir = dirname(resolve(file));
  while (dir !== "/") {
    if (existsSync(`${dir}/.git`)) return dir;
    dir = dirname(dir);
  }
  return null;
}

// ---- Secret scanning ----

// File names that are near-certainly secret containers when committed
const SECRET_NAME_RE =
  /(\.pem$|\.key$|id_rsa|id_ed25519|id_ecdsa|\.kdbx$|\.p12$|\.pfx$|keystore|service[-_]?account|\.env$)/i;

// Built-in fallback patterns (used when gitleaks is unavailable)
const SECRET_CONTENT_RES: RegExp[] = [
  /-----BEGIN [A-Z0-9 ]*PRIVATE KEY-----/,
  /\bAKIA[0-9A-Z]{16}\b/, // AWS access key
  /\bgh[pousr]_[A-Za-z0-9]{20,}\b/, // GitHub tokens
  /\bgithub_pat_[A-Za-z0-9_]{20,}\b/, // GitHub fine-grained PATs
  /\bsk-(ant-)?(proj-)?[A-Za-z0-9_-]{20,}\b/, // OpenAI/Anthropic style keys
  /\bxox[abprs]-[A-Za-z0-9-]{10,}\b/, // Slack tokens
  /\beyJ[A-Za-z0-9_-]{15,}\.[A-Za-z0-9_-]{15,}\.[A-Za-z0-9_-]{10,}\b/, // JWTs
  /\b(password|passwd|api[_-]?key|secret|token)\b\s*[:=]\s*["'][^"'\s]{8,}["']/i,
];

/**
 * Run gitleaks on a single file. Returns:
 *   true  — secret found
 *   false — clean
 *   null  — gitleaks unavailable (caller should use regex fallback)
 */
function gitleaksScan(file: string): boolean | null {
  try {
    execFileSync(
      "gitleaks",
      ["detect", "--no-git", "--source", file, "--exit-code", "1", "--no-banner"],
      { stdio: ["pipe", "pipe", "pipe"] },
    );
    return false;
  } catch (err: unknown) {
    const e = err as { code?: string | number; status?: number };
    // exit code 1 = leaks found (gitleaks ran successfully)
    if (e.status === 1) return true;
    // ENOENT / command not runnable → gitleaks not installed
    return null;
  }
}

/**
 * Scan a file for secrets. Returns a reason string when a secret is found,
 * null when the file is clean. Primary: gitleaks. Fallback: regex list plus
 * suspicious file names.
 */
function scanForSecrets(file: string): string | null {
  // gitleaks first (much better precision)
  const gitleaks = gitleaksScan(file);
  if (gitleaks === true) return "secret detected by gitleaks";
  if (gitleaks === false) return null;

  // Fallback 1: suspicious file name
  if (SECRET_NAME_RE.test(basename(file))) {
    return `file name looks like a secret container (${basename(file)})`;
  }

  // Fallback 2: content regexes
  try {
    const content = readFileSync(file, "utf-8");
    for (const re of SECRET_CONTENT_RES) {
      if (re.test(content)) return "secret pattern matched (fallback regex)";
    }
  } catch {
    // binary/unreadable — treat as clean, gitleaks is the real gate anyway
  }
  return null;
}

function isTrackedByGit(file: string, cwd: string): boolean {
  try {
    const out = execFileSync("git", ["ls-files", "--", file], {
      cwd,
      encoding: "utf-8",
      stdio: ["pipe", "pipe", "pipe"],
    }).trim();
    return out.length > 0;
  } catch {
    return false;
  }
}

/** Append the file path to the repo .gitignore (idempotent, creates if missing). */
function addToGitignore(gitRoot: string, file: string): boolean {
  try {
    const rel = relative(gitRoot, file);
    if (!rel || rel.startsWith("..")) return false;
    const gi = `${gitRoot}/.gitignore`;
    let existing = "";
    if (existsSync(gi)) {
      existing = readFileSync(gi, "utf-8");
      const already = existing
        .split("\n")
        .some((l) => l.trim() === rel || l.trim() === `/${rel}`);
      if (already) return false;
    } else {
      writeFileSync(gi, "");
    }
    const stamp = new Date().toISOString().slice(0, 10);
    appendFileSync(
      gi,
      `\n# added by safe-edit-backup ${stamp}: secret detected\n${rel}\n`,
    );
    return true;
  } catch {
    return false;
  }
}

// ---- Commit message generation (commitizen / conventional commits) ----

function normalizeSummary(text: string): string {
  let t = text
    .replace(/```[\s\S]+?```/g, " ") // strip code fences
    .replace(/`+/g, " ") // strip inline code ticks
    .replace(/^["'\s]+|["'\s]+$/g, ""); // strip outer quotes
  t = t.replace(/\s+/g, " ").trim(); // single line
  // clamp to 100 chars, prefer keeping the conventional prefix intact
  if (t.length > 100) t = t.slice(0, 100).trim();
  return t;
}

function withTimeout<T>(promise: Promise<T>, ms: number): Promise<T> {
  let timer: ReturnType<typeof setTimeout> | undefined;
  const timeout = new Promise<never>((_resolve, reject) => {
    timer = setTimeout(
      () => reject(new Error(`summarize timed out after ${ms}ms`)),
      ms,
    );
  });
  return Promise.race([promise, timeout]).finally(() => {
    if (timer) clearTimeout(timer);
  });
}

function pickSummaryModel(ctx: ExtensionContext): Model<Api> | null {
  // Fast cheap models, provider order matters (openrouter needs no session header)
  const preferred: Array<[string, string]> = [
    ["openrouter", "deepseek/deepseek-v4-flash"],
    ["opencode", "deepseek-v4-flash"],
  ];
  for (const [provider, modelId] of preferred) {
    const model = ctx.modelRegistry.find(provider, modelId);
    if (model && ctx.modelRegistry.hasConfiguredAuth(model)) return model;
  }
  // Last resort: cheapest available text-capable model
  const available = ctx.modelRegistry
    .getAvailable()
    .filter(
      (m: Model<Api>) =>
        m.input.includes("text") && ctx.modelRegistry.hasConfiguredAuth(m),
    );
  available.sort(
    (a: Model<Api>, b: Model<Api>) =>
      a.cost.input + a.cost.output - (b.cost.input + b.cost.output),
  );
  return available[0] ?? null;
}

/**
 * Ask a cheap model to summarize the diff (or the file content, for new
 * files) into a short Conventional Commits message. Returns null on any
 * failure so the caller can fall back to a numeric message.
 */
async function summarizeCommit(
  file: string,
  gitRoot: string,
  ctx: ExtensionContext,
): Promise<string | null> {
  const model = pickSummaryModel(ctx);
  if (!model) return null;

  // Detect brand-new (untracked) files
  let untracked = false;
  try {
    const status = execSync(`git status --porcelain -- "${file}"`, {
      cwd: gitRoot,
      encoding: "utf-8",
      stdio: ["pipe", "pipe", "pipe"],
    }).trim();
    untracked = status.startsWith("??");
  } catch {
    return null;
  }

  let payload: string;
  let instruction: string;
  try {
    if (untracked) {
      const content = readFileSync(file, "utf-8").slice(0, SUMMARY_PAYLOAD_CAP);
      if (content.trim().length === 0) return null; // empty new file
      payload = content;
      instruction = "This is a NEW file — describe what it adds or does.";
    } else {
      let diff = "";
      try {
        diff = execSync(`git diff HEAD --no-color -- "${file}"`, {
          cwd: gitRoot,
          encoding: "utf-8",
          stdio: ["pipe", "pipe", "pipe"],
        }).trim();
      } catch {
        // repo may have no commits yet — leave diff empty
      }
      if (!diff) return null; // nothing changed vs HEAD → fall back
      payload = diff.slice(0, SUMMARY_PAYLOAD_CAP);
      instruction = "Describe the change.";
    }
  } catch {
    return null;
  }

  const systemPrompt =
    "You write git commit messages for a developer's dotfiles and personal " +
    "projects, in Conventional Commits format (cz_conventional_commits " +
    "profile). Reply with ONLY the commit message: exactly one line, format " +
    "`type: subject` (or `type(scope): subject`), where type is one of " +
    "feat, fix, docs, style, refactor, perf, test, build, ci, chore, revert. " +
    "Subject in imperative mood, lowercase start, no quotes, no markdown, " +
    "no newlines, 72 characters max for the whole line.";

  const prompt = `${basename(file)}\n\n${instruction}\n\n---\n${payload}`;

  const context: Context = {
    systemPrompt,
    messages: [{ role: "user", content: prompt, timestamp: Date.now() }],
  };

  try {
    const stream: AssistantMessageEventStream = ctx.modelRegistry.streamSimple(
      model,
      context,
      { maxTokens: 120, temperature: 0.2 },
    );
    // Cast through the stream contract; inferred-settings checking can't
    // resolve EventStream.result()'s generic R to AssistantMessage.
    const message = (await withTimeout(
      stream.result(),
      SUMMARY_TIMEOUT_MS,
    )) as AssistantMessage;
    if (
      !message ||
      message.stopReason === "error" ||
      message.stopReason === "aborted"
    ) {
      return null;
    }
    const text = message.content
      .flatMap((part) => (part.type === "text" ? [part.text] : []))
      .join(" ")
      .trim();
    if (!text) return null;
    return normalizeSummary(text);
  } catch {
    return null;
  }
}

/**
 * Validate a commit message with commitizen's `cz check` (uses the
 * cz_conventional_commits profile / repo .cz.toml if present). Falls back to
 * a regex check when cz is not installed. Returns true when valid.
 */
function validateCommitMessage(msg: string): boolean {
  if (!CONVENTIONAL_RE.test(msg)) return false;
  try {
    const tmp = `${tmpdir()}/safe-edit-cz-check-${Date.now()}.msg`;
    writeFileSync(tmp, `${msg}\n`);
    try {
      execFileSync("cz", ["check", "--commit-msg-file", tmp], {
        stdio: ["pipe", "pipe", "pipe"],
      });
      return true;
    } finally {
      try {
        unlinkSync(tmp);
      } catch {
        // ignore
      }
    }
  } catch {
    // cz unavailable or rejected the message. If cz is installed but
    // rejected, this was already regex-validated — accept the regex verdict
    // to avoid blocking on cz config quirks.
    return CONVENTIONAL_RE.test(msg);
  }
}

async function generateCommitMessage(
  file: string,
  gitRoot: string,
  ctx: ExtensionContext,
): Promise<string> {
  const summarized = await summarizeCommit(file, gitRoot, ctx);
  if (summarized && validateCommitMessage(summarized)) return summarized;

  // Fallback: conventional numeric diff summary (or plain update)
  const base = basename(file);
  try {
    const result = execSync(`git diff --numstat "${file}"`, {
      cwd: gitRoot,
      encoding: "utf-8",
      stdio: ["pipe", "pipe", "pipe"],
    }).trim();
    if (result) {
      const [added, deleted] = result.split("\t");
      const a = parseInt(added || "0", 10);
      const d = parseInt(deleted || "0", 10);
      if (a > 0 && d > 0) return `chore: update ${base} (+${a}/-${d})`;
      if (a > 0) return `chore: update ${base} (+${a})`;
      if (d > 0) return `chore: update ${base} (-${d})`;
      return `chore: update ${base}`;
    }
  } catch {
    // git diff unavailable — fall through to a generic message
  }
  return `chore: update ${base}`;
}

// ---- Approval dialog ----

type ApprovalDecision = "commit" | "skip" | "always";

interface CommitPreview {
  tool: string; // "git" | "yadm" | "chezmoi"
  file: string;
  message: string;
  diff: string; // unified diff (may be empty for brand-new empty files)
  secretAlert?: string; // set when a secret blocked the commit
}

/** One-line-per-entry diff renderer; falls back gracefully when no theme. */
function renderDiffLines(diff: string, width: number, maxLines: number): {
  lines: string[];
  omitted: number;
} {
  const raw = diff.length ? diff.split("\n") : ["(no textual diff — new/empty file)"];
  const shown = raw.slice(0, maxLines).map((l) => truncateToWidth(l, width));
  const omitted = Math.max(0, raw.length - maxLines);
  return { lines: shown, omitted };
}

/**
 * Show the commit preview dialog: message + diff, then let the user choose.
 * Returns undefined when no TUI is available (headless) — callers treat that
 * as "skip" (fail-closed).
 */
async function askCommitApproval(
  ctx: ExtensionContext,
  preview: CommitPreview,
): Promise<ApprovalDecision | undefined> {
  if (ctx.mode !== "tui") {
    try {
      ctx.ui.notify(
        `safe-edit: commit SKIPPED (headless, no approval possible) for ${basename(preview.file)}`,
        "warning",
      );
    } catch {
      // no UI at all — still fail closed
    }
    return undefined;
  }

  try {
    return await ctx.ui.custom<ApprovalDecision | undefined>(
      (_tui, theme, _keybindings, done) => {
        let cachedWidth: number | undefined;
        let cachedLines: string[] | undefined;

        const invalidate = () => {
          cachedWidth = undefined;
          cachedLines = undefined;
        };

        return {
          render(width: number): string[] {
            if (cachedLines && cachedWidth === width) return cachedLines;
            cachedWidth = width;

            const head = [
              theme.fg("accent", `safe-edit-backup — ${preview.tool} commit approval`),
              `file: ${preview.file}`,
              theme.fg("accent", `message: ${preview.message}`),
              "",
            ];
            const { lines: diffLines, omitted } = renderDiffLines(
              preview.diff,
              width,
              DIFF_PREVIEW_LINES,
            );
            const tail = [
              ...(preview.secretAlert
                ? [theme.fg("accent", `ALERT: ${preview.secretAlert}`)]
                : []),
              ...(omitted > 0
                ? [theme.fg("dim", `… ${omitted} more diff lines omitted`)]
                : []),
              "",
              theme.fg(
                "dim",
                "[c] commit   [s] skip   [a] always this session (this file)   esc = skip",
              ),
            ].map((l) => truncateToWidth(l, width));

            cachedLines = [...head, ...diffLines, ...tail];
            return cachedLines;
          },
          handleInput(data: string): void {
            if (data === "c" || data === "C" || data === "y" || data === "Y") {
              done("commit");
            } else if (data === "a" || data === "A") {
              done("always");
            } else if (
              data === "s" ||
              data === "S" ||
              data === "\x1b" || // escape
              data === "\r" || // enter → fail-closed skip
              data === "\n"
            ) {
              done("skip");
            } else {
              return; // ignore other keys
            }
          },
          invalidate,
        };
      },
    );
  } catch {
    // Dialog unavailable/errored → fail closed
    try {
      ctx.ui.notify(
        `safe-edit: approval dialog failed — commit skipped for ${basename(preview.file)}`,
        "warning",
      );
    } catch {
      // ignore
    }
    return undefined;
  }
}

// ---- Git / yadm / chezmoi commit flows ----

async function gitCommitIfNeeded(
  file: string,
  ctx: ExtensionContext,
  approved: Set<string>,
): Promise<void> {
  // Resolve through symlinks (for Stow-managed files)
  let realFile: string;
  try {
    realFile = realpathSync(file);
  } catch {
    realFile = resolve(file);
  }
  const gitRoot = isInGitRepo(realFile);
  if (!gitRoot) return;
  if (!existsSync(realFile)) return;

  try {
    // Check if file has unstaged/uncommitted changes (also untracked)
    const status = execSync(`git status --porcelain -- "${realFile}"`, {
      cwd: gitRoot,
      encoding: "utf-8",
      stdio: ["pipe", "pipe", "pipe"],
    }).trim();
    if (!status) return;

    // ---- Layer 1: secret scan ----
    const secret = scanForSecrets(realFile);
    if (secret) {
      const tracked = isTrackedByGit(realFile, gitRoot);
      if (tracked) {
        // Skip + alert only; never change tracked state silently
        await askCommitApproval(ctx, {
          tool: "git",
          file: realFile,
          message: "(commit blocked)",
          diff: `SECRET DETECTED in a TRACKED file: ${realFile}\nReason: ${secret}\n\nNo commit was made. Handle manually, e.g.:\n  git rm --cached "${relative(gitRoot, realFile)}"\n  (rotate the secret, then commit the removal yourself)`,
          secretAlert: secret,
        });
        return;
      }
      // Untracked: add to .gitignore, no commit
      const added = addToGitignore(gitRoot, realFile);
      try {
        ctx.ui.notify(
          `safe-edit: ${secret} in ${basename(realFile)} — commit blocked${added ? `, added to .gitignore` : ""}`,
          "warning",
        );
      } catch {
        // no UI — still blocked, which is the important part
      }
      return;
    }

    // ---- Layer 2: commitizen-format message ----
    const msg = await generateCommitMessage(realFile, gitRoot, ctx);

    // ---- Layer 3: user approval with diff ----
    let diff = "";
    try {
      const untracked = status.startsWith("??");
      diff = untracked
        ? execFileSync("git", ["diff", "--no-index", "--no-color", "--", "/dev/null", realFile], {
            cwd: gitRoot,
            encoding: "utf-8",
            stdio: ["pipe", "pipe", "pipe"],
          }).trim()
        : execSync(`git diff HEAD --no-color -- "${realFile}"`, {
            cwd: gitRoot,
            encoding: "utf-8",
            stdio: ["pipe", "pipe", "pipe"],
          }).trim();
    } catch {
      // repo may have no commits yet — diff optional
    }

    const approvalKey = `git:${realFile}`;
    let decision: ApprovalDecision | undefined;
    if (approved.has(approvalKey)) {
      decision = "commit";
    } else {
      decision = await askCommitApproval(ctx, {
        tool: "git",
        file: realFile,
        message: msg,
        diff,
      });
    }

    if (decision === "always") approved.add(approvalKey);
    if (decision !== "commit" && decision !== "always") {
      if (decision === "skip") {
        try {
          ctx.ui.notify(
            `safe-edit: commit skipped for ${basename(realFile)} (file left unstaged)`,
            "info",
          );
        } catch {
          // ignore
        }
      }
      return;
    }

    // Stage and commit (only this file, not other pre-staged files).
    // Use execFileSync with separate args to avoid shell-quoting issues.
    execFileSync("git", ["add", "--", realFile], {
      cwd: gitRoot,
      stdio: "pipe",
    });
    execFileSync("git", ["commit", "-m", msg, "--no-gpg-sign", "--", realFile], {
      cwd: gitRoot,
      stdio: "pipe",
    });
    try {
      ctx.ui.notify(`safe-edit: committed ${basename(realFile)} — ${msg}`, "info");
    } catch {
      // ignore
    }
  } catch {
    // git commit is best-effort — never break the edit/write call
  }
}

function isYadmManaged(file: string): boolean {
  try {
    const result = execSync(`yadm status "${file}" 2>/dev/null`, {
      encoding: "utf-8",
      stdio: ["pipe", "pipe", "pipe"],
    });
    return result.trim().length > 0;
  } catch {
    return false;
  }
}

function yadmCommit(
  file: string,
  ctx: ExtensionContext,
  approved: Set<string>,
): void {
  if (!isYadmManaged(file)) return;

  // Secret scan — yadm files live in $HOME, be extra careful there
  const secret = scanForSecrets(file);
  if (secret) {
    try {
      ctx.ui.notify(
        `safe-edit: ${secret} in ${basename(file)} — yadm commit blocked`,
        "warning",
      );
    } catch {
      // ignore — still blocked
    }
    return;
  }

  const msg = `chore: update ${basename(file)}`;
  const approvalKey = `yadm:${file}`;
  const proceed = async () => {
    try {
      execFileSync("yadm", ["add", file], { stdio: "pipe" });
      execFileSync("yadm", ["commit", "-m", msg], { stdio: "pipe" });
      try {
        ctx.ui.notify(`safe-edit: committed (yadm) ${basename(file)} — ${msg}`, "info");
      } catch {
        // ignore
      }
    } catch {
      // yadm commit best-effort
    }
  };

  (async () => {
    if (approved.has(approvalKey)) return proceed();
    const diff = (() => {
      try {
        return execSync(`yadm diff --no-color "${file}" 2>/dev/null`, {
          encoding: "utf-8",
          stdio: ["pipe", "pipe", "pipe"],
        }).trim();
      } catch {
        return "";
      }
    })();
    const decision = await askCommitApproval(ctx, {
      tool: "yadm",
      file,
      message: msg,
      diff,
    });
    if (decision === "always") approved.add(approvalKey);
    if (decision === "commit" || decision === "always") await proceed();
  })().catch(() => {
    // never break the tool call
  });
}

