/**
 * safe-edit-backup — Automatic file backups and hardened git integration for edit/write tools
 *
 * Hooks into built-in edit and write tool calls to:
 * 1. Create timestamped backups before any modification
 * 2. Rotate backups (keep max 5 per file)
 * 3. Commit changes if the file is in a git repo (or yadm/chezmoi managed),
 *    gated behind THREE safety layers:
 *
 *    a) SECRET SCAN — every file that is about to be committed is scanned with
 *       `gitleaks detect --no-git` (falls back to a built-in regex list if the
 *       gitleaks binary is not installed). If a secret is detected:
 *         - file NOT tracked by git → NO commit; path is appended to the
 *           repo's .gitignore; user is notified.
 *         - file ALREADY tracked → NO commit; user is alerted to handle it
 *           manually (git rm --cached etc.); git state is never changed
 *           silently.
 *
 *    b) COMMITIZEN MESSAGE — commit messages are generated by a cheap model
 *       in Conventional Commits format (cz_conventional_commits, matching the
 *       user's nix-conf/.cz.toml profile: `type(scope): subject`, types
 *       feat|fix|docs|style|refactor|perf|test|build|ci|chore|revert) and
 *       validated with `cz check --commit-msg-file`. If generation/validate
 *       fails (or cz isn't installed → regex validation), the fallback is a
 *       numeric `chore: update <file> (+n/-n lines)` message.
 *
 *    c) USER APPROVAL — before any commit, a dialog shows the proposed
 *       message plus a unified diff of what changed. Options per commit:
 *         c = commit, s = skip, a = always (remember this session for the
 *         same file), esc/enter = skip (fail-closed). In headless/RPC/print
 *         sessions there is no dialog: commits are SKIPPED (fail-closed).
 *
 * BACKUPS: all backups live centrally under
 *   $XDG_DATA_HOME/safe-edit/backups/<encoded-full-path>/
 * (default ~/.local/share/safe-edit/backups) so project dirs and git
 * worktrees never accumulate .backups folders when iterating on files.
 *
 * DOTFILES CONVENTION:
 * - Managed via GNU Stow at ~/dotfiles/
 * - Each config is its own stow package (one dir = one package)
 * - Package structure: <name>/.config/<name>/<file>
 * - Install all: cd ~/dotfiles && stow *
 * - See ~/dotfiles/DOTFILES_CONVENTION.md
 *
 * PACKAGE INSTALLATION PREFERENCE:
 * - Always ask user: global (pacman) or nix/home-manager?
 *
 * External tools (all optional, degrade gracefully):
 * - gitleaks  — secret scanning (pacman: gitleaks)
 * - cz        — commit message validation (pipx: commitizen)
 */

